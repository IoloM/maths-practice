/**
 * Generates the template registry:
 *   src/content/templates/<CH>/index.ts   — concatenates the chapter's template files (one lazy chunk per chapter)
 *   src/content/templates/loaders.gen.ts  — lazy loaders for the app
 *   src/content/templates/all.gen.ts      — static imports for tests and scripts
 * Run: npx tsx scripts/gen-index.ts   (also runs before build/test)
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../src/content/templates');
const dirs = fs
  .readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && /^(P1|P2|SM1|SM2)-\d+$/.test(d.name))
  .map((d) => d.name)
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));

const header = '// AUTO-GENERATED by scripts/gen-index.ts — do not edit.\n';
for (const d of dirs) {
  const files = fs
    .readdirSync(path.join(root, d))
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .sort();
  const imports = files.map((f, i) => `import t${i} from './${f.replace(/\.ts$/, '')}';`).join('\n');
  const body = `${header}import type { Template } from '../../../engine/templates/types';\n${imports}\n\nconst templates: Template[] = [${files.map((_, i) => `...t${i}`).join(', ')}];\nexport default templates;\n`;
  fs.writeFileSync(path.join(root, d, 'index.ts'), body);
}
const ref = (d: string) => d.replace('-', '.');
fs.writeFileSync(
  path.join(root, 'loaders.gen.ts'),
  `${header}import type { Template } from '../../engine/templates/types';\n\nexport const loaders: Record<string, () => Promise<{ default: Template[] }>> = {\n${dirs.map((d) => `  '${ref(d)}': () => import('./${d}/index'),`).join('\n')}\n};\n`,
);
fs.writeFileSync(
  path.join(root, 'all.gen.ts'),
  `${header}import type { Template } from '../../engine/templates/types';\n${dirs.map((d, i) => `import c${i} from './${d}/index';`).join('\n')}\n\nexport const ALL_TEMPLATES: Template[] = [${dirs.map((_, i) => `...c${i}`).join(', ')}];\n\nexport const BY_CHAPTER: Record<string, Template[]> = {\n${dirs.map((d, i) => `  '${ref(d)}': c${i},`).join('\n')}\n};\n`,
);
console.log(`registry: ${dirs.length} chapters`);
